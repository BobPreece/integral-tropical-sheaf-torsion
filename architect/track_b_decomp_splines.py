def _rat_str(num: int, den: int) -> str:
    if den < 0:
        num = -num
        den = -den
    g = math.gcd(abs(num), den)
    nr = num // g
    dr = den // g
    return str(nr) if dr == 1 else f"{nr}/{dr}"


def _ceil_div(num: int, den: int) -> int:
    if den <= 0:
        raise ValueError("Denominator must be positive in _ceil_div")
    return -((-num) // den)


def _snf_cert_dict(A: Sequence[Sequence[int]], snf: SNFResult) -> dict[str, object]:
    return {
        "A": [[int(x) for x in row] for row in A],
        "U": snf.U,
        "U_inv": snf.U_inv,
        "S": snf.S,
        "V": snf.V,
        "V_inv": snf.V_inv,
        "invariant_factors": list(snf.invariant_factors),
    }


class _TrackBTimeout(RuntimeError):
    pass


def _alarm_handler(signum: int, frame: object) -> None:
    _ = (signum, frame)
    raise _TrackBTimeout("Track B stage exceeded 20s timeout")


def _timed_stage(name: str, fn: Callable[[], dict[str, object]]) -> dict[str, object]:
    prev = signal.signal(signal.SIGALRM, _alarm_handler)
    signal.alarm(20)
    t0 = time.monotonic_ns()
    try:
        res = fn()
    finally:
        signal.alarm(0)
        signal.signal(signal.SIGALRM, prev)
    elapsed_us = (time.monotonic_ns() - t0) // 1000
    out = dict(res)
    out["stage"] = name
    out["elapsed_us"] = elapsed_us
    return out


