def exact_elementary_cg_round(
    A_ge: Sequence[Sequence[int]],
    b_ge: Sequence[int],
) -> tuple[list[list[int]], list[int]]:
    """Compute exact simultaneous elementary Chvatal-Gomory closure P^(1) for P = {x : A_ge x >= b_ge}.

    Uses unimodular SNF of all nonsingular k x d constraint subsets (1 <= k <= d) to enumerate
    every rational multiplier lambda in [0, 1)^m with lambda^T A_ge in Z^d, deriving the exact
    rounded cut (lambda^T A_ge) x >= ceil(lambda^T b_ge), deduplicating parallel cuts by keeping
    the tightest RHS, and pruning LP-redundant inequalities.
    """
    m = len(A_ge)
    if m == 0:
        return ([], [])
    d = len(A_ge[0])

    # Dictionary mapping primitive integer normal c_prim -> max ceil_rhs (for primitive c_prim!)
    # Note: if lambda^T A_ge = g * c_prim with g > 1, we keep exact row c_vec -> b_cut, and
    # note c_prim . x >= ceil(b_cut / g) is ALREADY generated by (lambda / g) mod 1!
    best_cuts: dict[tuple[int, ...], int] = {}

    for i in range(m):
        row_t = tuple(int(v) for v in A_ge[i])
        p_dir, g = primitive_direction(row_t)
        if g == 0:
            continue
        rhs_p = _ceil_div(int(b_ge[i]), g)
        if p_dir not in best_cuts or rhs_p > best_cuts[p_dir]:
            best_cuts[p_dir] = rhs_p

    # Enumerate subsets I of size k in 1..min(d, m):
    # For each subset I of size k, we want all u in {1..D-1}^k (mod D) such that u^T A_I == 0 (mod D)!
    # Using SNF(A_I^T): U @ A_I^T @ V = S (d x k), if rank == k (full row rank of A_I),
    # let d_1..d_k be invariant factors and D = d_k!
    # Wait: A_I^T @ w in Z^d for w = V @ y (y_j = a_j / d_j, 0 <= a_j < d_j)!
    # Take w_mod_1 = (V @ [(D // d_j) * a_j]) mod D (strictly > 0 on all k components if non-degenerate,
    # or >= 0 -> valid non-negative multiplier lambda_I = w_mod_1 / D in [0, 1)^k!).
    for k_sz in range(2, min(d, m) + 1):
        for combo in itertools.combinations(range(m), k_sz):
            sub_A = [[int(A_ge[idx][c]) for c in range(d)] for idx in combo]
            sub_AT = [[sub_A[r_i][c_i] for r_i in range(k_sz)] for c_i in range(d)]
            snf = smith_normal_form(sub_AT, verify=False)
            if snf.rank < k_sz:
                continue
            inv_f = snf.invariant_factors
            d_max = inv_f[-1]
            if d_max <= 1:
                continue
            ranges = [range(df) for df in inv_f]
            for a_tup in itertools.product(*ranges):
                if all(v == 0 for v in a_tup):
                    continue
                # u_raw = V @ [(d_max // d_j) * a_j] mod d_max
                scaled_a = [(d_max // inv_f[j]) * a_tup[j] for j in range(k_sz)]
                u_mod = [val % d_max for val in mat_vec_mul(snf.V, scaled_a)]
                if all(v == 0 for v in u_mod):
                    continue
                c_raw = vec_mat_mul(u_mod, sub_A)
                if any(val % d_max != 0 for val in c_raw):
                    raise AssertionError("CG lattice multiplier failed integrality check")
                c_int = [val // d_max for val in c_raw]
                if all(val == 0 for val in c_int):
                    continue
                rhs_num = sum(u_mod[j] * int(b_ge[combo[j]]) for j in range(k_sz))
                rhs_cut = _ceil_div(rhs_num, d_max)
                p_dir, g_c = primitive_direction(c_int)
                rhs_prim = _ceil_div(rhs_cut, g_c)
                if p_dir not in best_cuts or rhs_prim > best_cuts[p_dir]:
                    best_cuts[p_dir] = rhs_prim

    cand_A = [list(k_dir) for k_dir in sorted(best_cuts.keys())]
    cand_b = [best_cuts[k_dir] for k_dir in sorted(best_cuts.keys())]

    # Prune redundant cuts via exact LP: A x >= b  <=>  (-A) x <= (-b), minimize c . x <=> maximize (-c) . x
    kept_A: list[list[int]] = []
    kept_b: list[int] = []
    for idx in range(len(cand_A)):
        other_A_ub = [[-v for v in row] for row in (kept_A + cand_A[idx + 1 :])]
        other_b_ub = [-v for v in (kept_b + cand_b[idx + 1 :])]
        if other_A_ub:
            # Minimize cand_A[idx] . x <=> maximize (-cand_A[idx]) . x
            lp = solve_lp(other_A_ub, other_b_ub, c_max=[-v for v in cand_A[idx]])
            # min_val = -obj_num / obj_den; redundant iff min_val >= cand_b[idx] <=> -obj_num >= cand_b[idx] * obj_den
            if lp.status == "OPTIMAL" and lp.obj_num is not None:
                if -lp.obj_num >= cand_b[idx] * lp.obj_den:
                    continue
        kept_A.append(cand_A[idx])
        kept_b.append(cand_b[idx])

    return (kept_A, kept_b)


def _enumerate_ge_vertices(
    A_ge: Sequence[Sequence[int]],
    b_ge: Sequence[int],
) -> list[tuple[tuple[int, ...], int]]:
    A_ub = [[-int(v) for v in row] for row in A_ge]
    b_ub = [-int(v) for v in b_ge]
    return enumerate_vertices(A_ub, b_ub)


