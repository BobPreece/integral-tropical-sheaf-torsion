def certify_theorem_b1() -> dict[str, object]:
    # 1. Verify 3-ray 2D fan collapse (dim B_Sigma = 3 - 2 = 1 => every balanced w is convex or concave)
    # Test on A_1 fan ((1,0), (-1,2), (0,-1)) and asymmetric 3-ray fan ((1,0), (1,3), (-2,-3)):
    three_ray_fans = {
        "A_1": ((1, 0), (-1, 2), (0, -1)),
        "asymmetric_det3": ((1, 0), (1, 3), (-2, -3)),
    }
    three_ray_results: dict[str, object] = {}
    for label, rays in three_ray_fans.items():
        # Verify strictly positive CCW cyclic spanning of R^2
        for idx in range(3):
            x1, y1 = rays[idx]
            x2, y2 = rays[(idx + 1) % 3]
            if x1 * y2 - y1 * x2 <= 0:
                raise AssertionError(f"3-ray fan {label} is not strictly positively spanning")
        eta_list = [primitive_direction((-ry, rx))[0] for (rx, ry) in rays]
        E_bal = [[eta_list[j][i] for j in range(3)] for i in range(2)]
        snf_e = smith_normal_form(E_bal)
        dim_b = 3 - snf_e.rank
        if dim_b != 1:
            raise AssertionError(f"Expected dim B_Sigma == 1 on 3-ray fan {label}, got {dim_b}")
        gen = [snf_e.V[r][2] for r in range(3)]
        if gen[0] < 0:
            gen = [-v for v in gen]
        # Every component MUST have identical strict positive sign!
        if not all(v > 0 for v in gen):
            raise AssertionError(f"Expected strictly positive 1D balanced generator on {label}, got {gen}")
        three_ray_results[label] = {
            "dim_B_Sigma": dim_b,
            "primitive_normals": [list(e) for e in eta_list],
            "positive_balanced_generator": gen,
            "all_balanced_already_convex_or_concave": True,
        }

    # 2. Sweep Reeve tetrahedra T_r = conv{(0,0,0), (1,0,0), (0,1,0), (1,1,r)} for r = 1..12
    reeve_sweep: list[dict[str, object]] = []
    sample_snf_certs: dict[str, object] = {}
    for r in range(1, 13):
        verts = [[0, 0, 0], [1, 0, 0], [0, 1, 0], [1, 1, r]]
        vol3 = normalized_lattice_volume_vertices(verts)
        if vol3 != r:
            raise AssertionError(f"Vol_3(T_{r}) = {vol3} != {r}")

        E_primal = [[1, 0, 0], [0, 1, 0], [1, 1, r]]
        snf_primal = smith_normal_form(E_primal)
        if snf_primal.invariant_factors != (1, 1, r):
            raise AssertionError(f"Primal SNF mismatch at r={r}: {snf_primal.invariant_factors}")

        # Polar primitive facet-form matrix: l_12 = z, l_13 = -r*y + z, l_23 = r*x - z
        L_polar = [[0, 0, 1], [0, -r, 1], [r, 0, -1]]
        for row in L_polar:
            if primitive_gcd(row) != 1:
                raise AssertionError("Polar facet form not primitive")
        snf_polar = smith_normal_form(L_polar)
        if snf_polar.invariant_factors != (1, r, r):
            raise AssertionError(f"Polar SNF mismatch at r={r}: {snf_polar.invariant_factors}")

        # 3 ridge colon 2x3 submatrices: (l_12, l_13), (l_12, l_23), (l_13, l_23) -> each SNF == (1, r)!
        ridge_snfs: list[list[int]] = []
        for i, j in ((0, 1), (0, 2), (1, 2)):
            snf_ridge = smith_normal_form([L_polar[i], L_polar[j]])
            if snf_ridge.invariant_factors != (1, r):
                raise AssertionError(f"Ridge colon SNF mismatch at r={r}: {snf_ridge.invariant_factors}")
            ridge_snfs.append(list(snf_ridge.invariant_factors))

        # Verify Weil \ Cart <-> Cartier BSS degree-1 equivalence on complete fan Sigma_r:
        # Rays v_1=(1,0,0), v_2=(0,1,0), v_3=(1,1,r), v_4=(0,0,-1); Weil ray-height c = (0, 0, k_h, 0)
        # lies in Cart(Sigma_r) <=> E_primal * a = (0, 0, k_h)^T solvable over Z <=> r | k_h <=> w^prim in Z!
        z_weil_gen = solve_over_z(E_primal, [0, 0, 1], snf=snf_primal)
        z_cart_mult = solve_over_z(E_primal, [0, 0, r], snf=snf_primal)
        if r > 1 and (z_weil_gen.status != "UNSAT_Z_TORSION" or z_weil_gen.obstruction_modulus != r):
            raise AssertionError(f"Expected Z/{r}Z Weil/Cartier obstruction at r={r}")
        if z_cart_mult.status != "CERTIFIED_EXACT" or z_cart_mult.solution_z != (0, 0, 1):
            raise AssertionError(f"Cartier BSS spline lift failed for r*D_3 at r={r}")

        if r in (2, 5, 12):
            sample_snf_certs[f"T_{r}_primal"] = _snf_cert_dict(E_primal, snf_primal)
            sample_snf_certs[f"T_{r}_polar"] = _snf_cert_dict(L_polar, snf_polar)

        reeve_sweep.append({
            "r": r,
            "vol3": vol3,
            "primal_snf": list(snf_primal.invariant_factors),
            "polar_snf": list(snf_polar.invariant_factors),
            "ridge_colon_snfs": ridge_snfs,
            "weil_mod_cartier": "0" if r == 1 else f"Z/{r}Z",
            "weil_gen_wall_jump": _rat_str(1, r),
            "cartier_dc_hull_empty_for_non_cartier": r > 1,
        })

    return {
        "theorem_id": "B1",
        "epistemic_status": "CERTIFIED_EXACT",
        "three_ray_collapse": three_ray_results,
        "reeve_control_r1": reeve_sweep[0],
        "reeve_sweep_r_2_to_12": reeve_sweep[1:],
        "unimodular_snf_certificates": sample_snf_certs,
    }


